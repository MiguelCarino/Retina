// ---------- Fleet-convention helpers ([data-i18n] leaves) ----------
function currentFleetLang() { return (window.CarinoLang && window.CarinoLang.current) || 'en'; }

function t(key) {
    const lang = currentFleetLang();
    if (lang === 'en' || !key) return key;
    const d = I18N[lang];
    return (d && d[key] != null) ? d[key] : key;
}

function applyStaticI18n() {
    document.querySelectorAll('[data-i18n]').forEach((el) => {
        // The key is sniffed from the element's own text on first sight, which is only
        // safe while that text is still the English source. Anything that writes the
        // element before the first pass — another applier, or a click handler setting a
        // label — would otherwise be cached AS the key, pinning it to that language for
        // the rest of the session. Trust the attribute when it carries the key itself,
        // and only sniff when the dictionary agrees the text is a source string.
        const d = el.dataset;
        if (!d.i18nKey) {
            const declared = (d.i18n || '').trim();
            const seen = el.textContent.trim();
            d.i18nKey = declared || seen;
        }
        el.textContent = t(d.i18nKey);
    });
}

// carino-lang.js is deferred and executes before this script (also deferred,
// placed after it), so CarinoLang exists by DOMContentLoaded. The app's own
// applier (inside index.html) wires itself to the same events for everything
// that is not a [data-i18n] leaf.
document.addEventListener('DOMContentLoaded', applyStaticI18n);
window.addEventListener('carino:langchange', applyStaticI18n);

window.t = t;
window.applyStaticI18n = applyStaticI18n;
